const findIP = (str) => {
    const ipRegex = /^(?:(?:25[0-5]|2[0-4]\d|1\d{2}|[1-9]\d|[1-9])\.(?:25[0-5]|2[0-4]\d|1\d{2}|[1-9]\d|[1-9])\.(?:25[0-5]|2[0-4]\d|1\d{2}|[1-9]\d|[1-9])\.(?:25[0-5]|2[0-4]\d|1\d{2}|[1-9]\d|[1-9]))(:[10-65535])?$/;
    return str.match(ipRegex);
  };